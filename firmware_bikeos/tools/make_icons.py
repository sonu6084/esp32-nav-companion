#!/usr/bin/env python3
"""
Draws the weather icon set with PIL (4x supersampled) and writes LVGL 8 images
(LVGL 9: LV_COLOR_FORMAT_ARGB8888, one copy of the pixels; LVGL converts to
the display's RGB565 when drawing).

  python3 tools/make_icons.py main/icons  [--png docs/icons.png]
"""
import sys, os, math
from PIL import Image, ImageDraw

SS = 4
SUN, MOON, CLOUD, CLOUD_D = (255, 193, 7), (255, 224, 130), (236, 239, 241), (144, 164, 174)
RAIN, SNOW, BOLT, FOG = (79, 195, 247), (255, 255, 255), (255, 214, 0), (176, 190, 197)

def canvas(S): return Image.new("RGBA", (S, S), (0, 0, 0, 0))

def sun(d, S, cx, cy, r, rays=True):
    if rays:
        for i in range(8):
            a = i * math.pi / 4
            x0, y0 = cx + math.cos(a) * r * 1.35, cy + math.sin(a) * r * 1.35
            x1, y1 = cx + math.cos(a) * r * 1.85, cy + math.sin(a) * r * 1.85
            d.line((x0, y0, x1, y1), fill=SUN, width=int(r * 0.28))
            for (x, y) in ((x0, y0), (x1, y1)):
                rr = r * 0.14
                d.ellipse((x - rr, y - rr, x + rr, y + rr), fill=SUN)
    d.ellipse((cx - r, cy - r, cx + r, cy + r), fill=SUN)

def moon(img, S, cx, cy, r):
    m = canvas(S); md = ImageDraw.Draw(m)
    md.ellipse((cx - r, cy - r, cx + r, cy + r), fill=MOON)
    md.ellipse((cx - r * 0.35, cy - r * 1.15, cx + r * 1.45, cy + r * 0.65), fill=(0, 0, 0, 0))
    img.alpha_composite(m)

def cloud(d, S, ox, oy, k, col):
    """cloud anchored with its base centre at (ox, oy), scale k (fraction of S)."""
    u = S * k
    d.rounded_rectangle((ox - u * 0.9, oy - u * 0.55, ox + u * 0.9, oy), radius=u * 0.27, fill=col)
    for cx, cy, r in ((-0.35, -0.52, 0.36), (0.22, -0.68, 0.48)):
        d.ellipse((ox + (cx - r) * u, oy + (cy - r) * u, ox + (cx + r) * u, oy + (cy + r) * u), fill=col)

def drops(d, S, ox, oy, u, kind):
    for i, dx in enumerate((-0.55, 0.0, 0.55)):
        x, y = ox + dx * u, oy + (0.25 + (i % 2) * 0.18) * u
        if kind == "rain":
            d.line((x + 0.12 * u, y, x - 0.08 * u, y + 0.42 * u), fill=RAIN, width=int(u * 0.13))
        elif kind == "drizzle":
            r = u * 0.08
            d.ellipse((x - r, y + 0.1 * u - r, x + r, y + 0.1 * u + r), fill=RAIN)
            d.ellipse((x - r, y + 0.36 * u - r, x + r, y + 0.36 * u + r), fill=RAIN)
        elif kind == "snow":
            r = u * 0.16
            for a in range(3):
                t = a * math.pi / 3
                d.line((x - math.cos(t) * r, y + 0.25 * u - math.sin(t) * r,
                        x + math.cos(t) * r, y + 0.25 * u + math.sin(t) * r), fill=SNOW, width=int(u * 0.07))

def draw(name, S):
    img = canvas(S); d = ImageDraw.Draw(img)
    c = S / 2
    if name == "clear_day":
        sun(d, S, c, c, S * 0.2)
    elif name == "clear_night":
        moon(img, S, c, c, S * 0.32)
    elif name in ("partly_day", "partly_night"):
        if name == "partly_day": sun(d, S, S * 0.38, S * 0.36, S * 0.15)
        else: moon(img, S, S * 0.38, S * 0.36, S * 0.22); d = ImageDraw.Draw(img)
        cloud(d, S, S * 0.58, S * 0.84, 0.30, CLOUD)
    elif name == "cloudy":
        cloud(d, S, S * 0.62, S * 0.62, 0.2, CLOUD_D)
        cloud(d, S, S * 0.47, S * 0.80, 0.27, CLOUD)
    elif name == "fog":
        cloud(d, S, S * 0.5, S * 0.55, 0.26, CLOUD_D)
        for i, (x0, x1) in enumerate(((0.15, 0.85), (0.22, 0.78), (0.15, 0.7))):
            y = S * (0.66 + i * 0.1)
            d.line((S * x0, y, S * x1, y), fill=FOG, width=int(S * 0.055))
    elif name in ("drizzle", "rain", "snow", "thunder"):
        col = CLOUD_D if name == "thunder" else CLOUD
        cloud(d, S, S * 0.5, S * 0.6, 0.27, col)
        if name == "thunder":
            u = S
            pts = [(0.52, 0.58), (0.38, 0.80), (0.49, 0.80), (0.42, 0.97), (0.64, 0.72), (0.52, 0.72), (0.60, 0.58)]
            d.polygon([(x * u, y * u) for x, y in pts], fill=BOLT)
        else:
            drops(d, S, S * 0.5, S * 0.6, S * 0.27, name)
    elif name == "unknown":
        cloud(d, S, S * 0.5, S * 0.75, 0.27, CLOUD_D)
    return img

NAMES = ["unknown", "clear_day", "clear_night", "partly_day", "partly_night",
         "cloudy", "fog", "drizzle", "rain", "snow", "thunder"]
SIZES = [120, 56]

def px_bytes(img, mode):
    out = bytearray()
    for r, g, b, a in img.get_flattened_data() if hasattr(img, 'get_flattened_data') else img.getdata():
        if mode == 32:
            out += bytes((b, g, r, a))
        else:
            v = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
            out += bytes(((v >> 8) & 0xFF, v & 0xFF, a)) if mode == "16s" else bytes((v & 0xFF, (v >> 8) & 0xFF, a))
    return out

def c_array(b):
    return "\n".join("    " + ", ".join(f"0x{x:02x}" for x in b[i:i + 24]) + "," for i in range(0, len(b), 24))

def main():
    outdir = sys.argv[1]
    os.makedirs(outdir, exist_ok=True)
    sheet = []
    with open(os.path.join(outdir, "wx_icons.c"), "w") as f, open(os.path.join(outdir, "wx_icons.h"), "w") as h:
        h.write("#pragma once\n/* Generated by tools/make_icons.py */\n#include \"lvgl.h\"\n\ntypedef enum {\n")
        for n in NAMES: h.write(f"    WX_ICON_{n.upper()},\n")
        h.write("    WX_ICON_COUNT\n} wx_icon_t;\n\n")
        for s in SIZES: h.write(f"extern const lv_image_dsc_t *const wx_icons_{s}[WX_ICON_COUNT];\n")
        f.write("/* Generated by tools/make_icons.py — do not edit */\n#include \"wx_icons.h\"\n\n")
        for s in SIZES:
            for n in NAMES:
                img = draw(n, s * SS).resize((s, s), Image.LANCZOS)
                sheet.append(img)
                sym = f"wx_{n}_{s}"
                f.write(f"static LV_ATTRIBUTE_LARGE_CONST const uint8_t {sym}_map[] = {{\n")
                f.write(c_array(px_bytes(img, 32)) + "\n};\n")
                f.write(f"static const lv_image_dsc_t {sym} = {{\n"
                        f"    .header = {{ .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_ARGB8888,\n"
                        f"                .w = {s}, .h = {s}, .stride = {s * 4} }},\n"
                        f"    .data_size = sizeof({sym}_map), .data = {sym}_map }};\n\n")
            f.write(f"const lv_image_dsc_t *const wx_icons_{s}[WX_ICON_COUNT] = {{\n")
            for n in NAMES: f.write(f"    &wx_{n}_{s},\n")
            f.write("};\n\n")
    if "--png" in sys.argv:
        p = sys.argv[sys.argv.index("--png") + 1]
        W = 120 * len(NAMES)
        g = Image.new("RGBA", (W, 120 + 56), (0, 0, 0, 255))
        for i, im in enumerate(sheet[:len(NAMES)]): g.alpha_composite(im, (i * 120, 0))
        for i, im in enumerate(sheet[len(NAMES):]): g.alpha_composite(im, (i * 120 + 32, 120))
        g.save(p)
    print("icons:", len(NAMES), "x", SIZES)

main()
