#!/usr/bin/env python3
"""
Minimal TTF -> LVGL font (.c) converter (bpp 4, uncompressed). Output builds on LVGL 8 and 9.
Used for large digits; LVGL's built-in Montserrat stops at 48 px.

  python3 tools/make_font.py <font.ttf> <size> <ranges> <name> <out.c>
  ranges: comma list of code points or spans, e.g. "0x2D,0x30-0x3A,0xB0"
"""
import sys
from PIL import ImageFont, Image, ImageDraw

ttf, size, rspec, name, out = sys.argv[1], int(sys.argv[2]), sys.argv[3], sys.argv[4], sys.argv[5]
ranges = []
for part in rspec.split(","):
    a, _, b = part.partition("-")
    ranges.append((int(a, 0), int(b or a, 0)))

font = ImageFont.truetype(ttf, size)
ascent, descent = font.getmetrics()

bitmap = []
glyphs = [(0, 0, 0, 0, 0, 0)]          # glyph id 0 is reserved
cmaps = []                              # (first, last, glyph_id_start)
for first, last in ranges:
    cmaps.append((first, last, len(glyphs)))
    for cp in range(first, last + 1):
        ch = chr(cp)
        x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        adv = round(font.getlength(ch) * 16)
        start = len(bitmap)
        if w and h:
            im = Image.new("L", (w, h), 0)
            ImageDraw.Draw(im).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
            nib = [p >> 4 for p in im.tobytes()]
            if len(nib) % 2:
                nib.append(0)
            bitmap += [(nib[i] << 4) | nib[i + 1] for i in range(0, len(nib), 2)]
        glyphs.append((start, adv, w, h, x0, -y1))

with open(out, "w") as f:
    f.write(f"/* Generated by tools/make_font.py: {ttf.split('/')[-1]} {size}px [{rspec}] bpp4 */\n")
    f.write('#include "lvgl.h"\n\n')
    f.write("static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {\n")
    for i in range(0, len(bitmap), 24):
        f.write("    " + ", ".join(f"0x{b:02x}" for b in bitmap[i:i + 24]) + ",\n")
    f.write("};\n\nstatic const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {\n")
    for g in glyphs:
        f.write("    {.bitmap_index = %d, .adv_w = %d, .box_w = %d, .box_h = %d, .ofs_x = %d, .ofs_y = %d},\n" % g)
    f.write("};\n\nstatic const lv_font_fmt_txt_cmap_t cmaps[] = {\n")
    for first, last, gid in cmaps:
        f.write(f"    {{ .range_start = {first}, .range_length = {last - first + 1}, .glyph_id_start = {gid}, "
                f".unicode_list = NULL, .glyph_id_ofs_list = NULL, .list_length = 0, "
                f".type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY }},\n")
    f.write("};\n\n")
    f.write(f"""static const lv_font_fmt_txt_dsc_t font_dsc = {{
    .glyph_bitmap = glyph_bitmap, .glyph_dsc = glyph_dsc, .cmaps = cmaps,
    .kern_dsc = NULL, .kern_scale = 0, .cmap_num = {len(cmaps)}, .bpp = 4, .kern_classes = 0, .bitmap_format = 0,
}};

const lv_font_t {name} = {{
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = {ascent + descent}, .base_line = {descent},
    .subpx = LV_FONT_SUBPX_NONE, .underline_position = 0, .underline_thickness = 0,
#if LVGL_VERSION_MAJOR >= 9
    .static_bitmap = 1,
    .fallback = NULL,
#endif
    .dsc = &font_dsc,
}};
""")
print(f"{out}: {len(glyphs) - 1} glyphs, {len(bitmap)} bytes")
